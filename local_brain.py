# 最近用过的台词（避免同一句连着冒两次）
_RECENT = []
_RECENT_MAX = 4


def _pick(pool):
    """从模板池挑一句，尽量避开最近用过的；没有可避的就用随机那句。"""
    fresh = [p for p in pool if p not in _RECENT]
    choice = random.choice(fresh if fresh else pool)
    _RECENT.append(choice)
    del _RECENT[:-_RECENT_MAX]
    return choice


def _period():
    h = int(time.strftime("%H"))
    if h < 5:
        return "deepnight"
    if h < 11:
        return "morning"
    if h < 14:
        return "noon"
    if h < 18:
        return "afternoon"
    if h < 23:
        return "evening"
    return "night"


